//! The VelaOS font engine: packed outlines in, antialiased pixels out.
//!
//! # What this crate is
//!
//! Three stages of one pipeline, each independently testable:
//!
//! * [`packed`] — a compact, validated reader for VelaOS's own outline format
//!   (`.velafont` blobs, produced from real font files by `tools/fonttool`).
//!   The format stores **quadratic Bézier outlines in font units**, which is
//!   what makes arbitrary scaling possible: the outline is resolution-free,
//!   and every pixel size is derived from it at render time.
//! * scaling — font-unit outlines mapped to 26.6 fixed-point pixels, with
//!   TrueType's implied on-curve midpoints reconstructed and each quadratic
//!   flattened to line segments within a sub-pixel error tolerance.
//! * [`raster`] — a scanline rasteriser with the TrueType **non-zero winding
//!   rule** and 8×8 supersampling (64 coverage levels), so diagonal edges are
//!   antialiased rather than stair-stepped.
//!
//! # Why vectors, not bitmaps
//!
//! A bitmap font is fixed to one size: 8×16 stays 8×16, and anything else is
//! either cropped or blocky. An outline font stores the *shape*, so one blob
//! renders crisply at any size the caller asks for — a 16-pixel terminal and
//! a 32-pixel heading share the same data.
//!
//! # Provenance
//!
//! The embedded blobs are subsets (printable ASCII) of real, freely licensed
//! typefaces, generated by `tools/fonttool` and committed as assets:
//!
//! * `sarasa-mono` — Sarasa Mono SC ([Sarasa Gothic](https://github.com/be5invis/Sarasa-Gothic),
//!   SIL OFL 1.1), the terminal font.
//! * `source-sans` — Source Sans 3 ([Adobe](https://github.com/adobe-fonts/source-sans),
//!   SIL OFL 1.1), the proportional UI font.
//! * `iosevka` — Iosevka ([Iosevka](https://github.com/be5invis/Iosevka),
//!   SIL OFL 1.1), the narrow coding font.

#![no_std]

extern crate alloc;

pub mod packed;
pub mod raster;

use alloc::vec::Vec;

/// A parsed `.velafont` blob, borrowed from wherever it is embedded.
#[derive(Clone)]
pub struct Font<'a> {
    data: &'a [u8],
    header: packed::Header,
}

impl<'a> Font<'a> {
    /// Parse and validate a blob.
    ///
    /// Returns `None` when the bytes are not a VelaOS font or are truncated:
    /// a caller must fall back to another font rather than panic, because a
    /// bad asset is a build mistake, not a runtime emergency.
    pub fn parse(data: &'a [u8]) -> Option<Font<'a>> {
        let header = packed::Header::read(data)?;
        Some(Font { data, header })
    }

    /// Font units per em — the scale every other measurement is relative to.
    pub fn units_per_em(&self) -> u16 {
        self.header.units_per_em
    }

    /// The typographic ascender, in font units above the baseline.
    pub fn ascender(&self) -> i16 {
        self.header.ascender
    }

    /// The typographic descender, in font units below the baseline (≤ 0).
    pub fn descender(&self) -> i16 {
        self.header.descender
    }

    /// Extra line spacing, in font units.
    pub fn line_gap(&self) -> i16 {
        self.header.line_gap
    }

    /// The height of one text line at `size` pixels, rounded to whole pixels.
    ///
    /// This is what a terminal divides the screen height by: the line box is
    /// ascender + |descender| + line gap, so text rendered line after line
    /// never overlaps.
    pub fn line_height(&self, size: u32) -> u32 {
        let upem = self.header.units_per_em as i32 as i64;
        let span = self.header.ascender as i32 as i64 - self.header.descender as i32 as i64
            + self.header.line_gap as i32 as i64;
        ((span * size as i64).div_round(upem.max(1))) as u32
    }

    /// The glyph mapped to `ch`, or `None` when the font has none.
    ///
    /// Callers decide their own fallback (a font with a `?` substitutes it
    /// through [`Font::glyph_or_default`]); the engine never invents shapes.
    pub fn glyph(&self, ch: char) -> Option<FontGlyph<'a>> {
        let index = self.header.charmap_lookup(self.data, ch)?;
        Some(self.glyph_by_index(index))
    }

    /// The glyph for `ch`, or the blob's default glyph when it has none.
    ///
    /// The default is the generator's substitution glyph (usually `?`), so an
    /// out-of-subset character renders as something honest instead of as a
    /// blank or as neighbouring text.
    pub fn glyph_or_default(&self, ch: char) -> FontGlyph<'a> {
        match self.glyph(ch) {
            Some(g) => g,
            None => self.glyph_by_index(self.header.default_glyph),
        }
    }

    /// The pixel width of `text` at `size`: the sum of its glyphs' advances,
    /// rounded per glyph the way [`FontGlyph::advance`] rounds. This is what
    /// a caller uses to centre or right-align a string before drawing it.
    pub fn text_width(&self, text: &str, size: u32) -> u32 {
        text.chars()
            .map(|ch| self.glyph_or_default(ch).advance(size))
            .sum()
    }

    /// The glyph at `index`, which the charmap produced.
    ///
    /// An out-of-range index is a broken blob; the caller gets an empty
    /// (advance-only) glyph rather than a panic.
    pub fn glyph_by_index(&self, index: u16) -> FontGlyph<'a> {
        let record = packed::GlyphRecord::read(self.data, &self.header, index);
        FontGlyph {
            font: self.clone(),
            index,
            record,
        }
    }
}

/// One glyph: its metrics plus the outline that draws it.
pub struct FontGlyph<'a> {
    font: Font<'a>,
    #[allow(dead_code)]
    index: u16,
    record: packed::GlyphRecord,
}

impl FontGlyph<'_> {
    /// The glyph's index inside its font.
    pub fn index(&self) -> u16 {
        self.index
    }

    /// Horizontal advance in font units.
    pub fn advance_units(&self) -> i32 {
        self.record.advance
    }

    /// Horizontal advance at `size` pixels, rounded to whole pixels.
    ///
    /// Rounding per glyph rather than per string is what keeps monospaced
    /// text monospaced: every glyph of the terminal font rounds the same
    /// way, so the grid stays a grid.
    pub fn advance(&self, size: u32) -> u32 {
        let upem = self.font.units_per_em() as i32 as i64;
        (((self.record.advance as i64) * size as i64).div_round(upem.max(1))) as u32
    }

    /// Render the glyph's outline at `size` pixels.
    ///
    /// Returns `None` for a blank glyph (a space): there is no bitmap to
    /// draw, and the caller advances by [`FontGlyph::advance`] regardless.
    /// The bitmap's origin is the glyph's bounding box, offset from the
    /// baseline by [`RasterGlyph::top`] (up) and [`RasterGlyph::left`]
    /// (right); a renderer blits it at `pen_x + left, baseline - top`.
    pub fn render(&self, size: u32) -> Option<RasterGlyph> {
        if self.record.points == 0 {
            return None;
        }
        let upem = self.font.units_per_em() as i32;
        if upem == 0 {
            return None;
        }
        // Fixed 26.6 scale factors, like FreeType: 1/64 pixel per unit step,
        // which keeps sub-pixel positioning exact through the rasteriser.
        let sx = ((size as i64) << 6) / upem as i64;
        let sy = ((size as i64) << 6) / upem as i64;
        let outline = self.record.outline(self.font.data);
        let path = outline.flatten(sx, sy);
        raster::rasterize(&path)
    }
}

/// One rendered glyph: antialiased coverage for its bounding box.
pub struct RasterGlyph {
    /// Bitmap width in pixels.
    pub width: u32,
    /// Bitmap height in pixels.
    pub height: u32,
    /// Offset left of the pen position, in pixels.
    pub left: i32,
    /// Offset up from the baseline, in pixels.
    pub top: i32,
    /// `width * height` coverage bytes, 0 (no ink) to 255 (full ink),
    /// row-major from the top-left corner.
    pub coverage: Vec<u8>,
}

impl RasterGlyph {
    /// Blending coverage for the pixel at (`x`, `y`), or 0 outside the box.
    pub fn coverage(&self, x: i32, y: i32) -> u8 {
        if x < 0 || y < 0 || x >= self.width as i32 || y >= self.height as i32 {
            return 0;
        }
        self.coverage[(y as usize) * self.width as usize + x as usize]
    }
}

/// `i64` division rounded away from zero by magnitude, the way metric
/// rounding wants it (half a pixel goes up, never down).
trait DivRound {
    fn div_round(self, rhs: Self) -> Self;
}

impl DivRound for i64 {
    fn div_round(self, rhs: Self) -> Self {
        let q = self / rhs;
        let r = self % rhs;
        if r * 2 >= rhs.abs() {
            q + 1
        } else if r * 2 <= -rhs.abs() {
            q - 1
        } else {
            q
        }
    }
}

/// The embedded terminal font: Sarasa Mono SC, printable ASCII.
pub fn sarasa_mono() -> Option<Font<'static>> {
    Font::parse(SARASA_MONO)
}

/// The embedded proportional UI font: Source Sans 3, printable ASCII.
pub fn source_sans() -> Option<Font<'static>> {
    Font::parse(SOURCE_SANS)
}

/// The embedded narrow coding font: Iosevka, printable ASCII.
pub fn iosevka() -> Option<Font<'static>> {
    Font::parse(IOSEVKA)
}

